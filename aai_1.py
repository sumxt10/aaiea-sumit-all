# ============================================================
# OPTIMIZATION 7: RETRY WITH BACKOFF
# ============================================================

import time
import random


def optimization_7(query, max_retries=2):

    model = genai.GenerativeModel(
        "gemini-flash-latest",
        system_instruction=TUTOR_SYSTEM_PROMPT
    )

    for attempt in range(max_retries + 1):

        try:

            response = model.generate_content(
                query,
                generation_config=genai.GenerationConfig(
                    response_mime_type="application/json",
                    temperature=0.2
                )
            )

            data = json.loads(response.text)

            # Check whether JSON matches our Pydantic schema
            TutorResponse(**data)

            print("Successful attempt:", attempt + 1)

            return data

        except Exception as e:

            print(
                "Attempt",
                attempt + 1,
                "failed:",
                str(e)[:100]
            )

            if attempt == max_retries:
                break

            # Increasing delay
            delay = (2 ** attempt) + random.uniform(0, 0.5)

            print(
                f"Waiting {delay:.2f} seconds before retry..."
            )

            time.sleep(delay)

    return {
        "topic": "Error",
        "definition": "Unable to generate a valid response.",
        "key_points": None,
        "example": "N/A",
        "summary": "Maximum retry limit reached."
    }


