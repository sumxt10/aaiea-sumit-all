def optimization_3(query):

    q = query.lower()

    # Custom intent detection for MY tutor
    if any(word in q for word in [
        "cause",
        "why",
        "reason",
        "how does",
        "how do"
    ]):
        intent = "explanation"

    elif any(word in q for word in [
        "steps",
        "procedure",
        "process",
        "how to"
    ]):
        intent = "procedure"

    elif any(word in q for word in [
        "example",
        "real world",
        "example of"
    ]):
        intent = "example"

    elif any(word in q for word in [
        "compare",
        "difference",
        "versus",
        " vs "
    ]):
        intent = "comparison"

    else:
        intent = "general"

    # Customize the prompt according to detected intent
    if intent == "explanation":
        extra_prompt = """
Focus mainly on explaining the causes, reasons,
and underlying concepts in a clear and simple manner.
"""

    elif intent == "procedure":
        extra_prompt = """
Focus on providing a clear step-by-step explanation
of the requested process or procedure.
"""

    elif intent == "example":
        extra_prompt = """
Focus on giving a simple practical or real-world example
to make the concept easy to understand.
"""

    elif intent == "comparison":
        extra_prompt = """
Clearly explain the similarities and differences
between the requested concepts.
"""

    else:
        extra_prompt = """
Give a balanced general-information explanation with
a definition, important points, and an example.
"""

    dynamic_prompt = TUTOR_SYSTEM_PROMPT + "\n" + extra_prompt

    model = genai.GenerativeModel(
        "gemini-flash-latest",
        system_instruction=dynamic_prompt
    )

    response = model.generate_content(
        query,
        generation_config=genai.GenerationConfig(
            response_mime_type="application/json",
            temperature=0.2
        )
    )

    return json.loads(response.text), intent


