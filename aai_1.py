# ============================================================
# OPTIMIZATION 10: RESPONSE REFINEMENT
# ============================================================

def optimization_10(data):

    # Clean key points
    if isinstance(data.get("key_points"), list):

        cleaned_points = []

        for point in data["key_points"]:

            point = str(point).strip()

            if point and point not in cleaned_points:
                cleaned_points.append(point)

        data["key_points"] = cleaned_points

    # Clean text fields
    fields = [
        "topic",
        "definition",
        "example",
        "summary"
    ]

    for field in fields:

        if isinstance(data.get(field), str):

            data[field] = data[field].strip()

    return data


